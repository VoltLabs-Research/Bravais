/**
 * Style-related props shared by all box-like primitives: `Box`, `Row`, `Stack`,
 * `Surface`, `Card`, `Alert`, etc.
 *
 * Every token resolves through an explicit lookup table below, and that is a hard
 * requirement rather than a style preference: these classes are generated by
 * Tailwind, whose scanner only recognises a class name it can see as a complete
 * literal in a source file. The previous implementation built them by
 * concatenation (`\`gap-${props.gap}\``), which a scanner cannot follow — every
 * such utility would silently fail to be generated. Adding a token means adding
 * a row to a table here, never interpolating one.
 */
export interface BoxStyleProps {
    display?: Display;
    direction?: FlexDirection;
    align?: AlignItems;
    justify?: JustifyContent;
    wrap?: boolean;
    gap?: GapToken;

    p?: PaddingToken;
    px?: PaddingXToken;
    py?: PaddingYToken;

    m?: '0';
    mt?: MarginTopToken;
    mb?: MarginBottomToken;
    mx?: MarginXToken;

    bg?: BackgroundToken;
    radius?: RadiusToken;
    border?: BorderToken;
    position?: PositionToken;
    overflow?: OverflowToken;

    width?: WidthToken;
    height?: HeightToken;
    maxW?: MaxWidthToken;
    maxH?: MaxHeightToken;
    flex?: FlexToken;

    textAlign?: TextAlign;

    /**
     * The nowrap + ellipsis + overflow-hidden triad. `Text` has always had this;
     * box-like primitives did not, which is why apps kept writing it by hand on
     * the wrapper that actually owns the width constraint.
     */
    truncate?: boolean;

    shrink?: '0';
    minH?: '0';
    minW?: '0';

    inset?: '0';
    top?: '0' | '1';
    left?: '0' | '1';
    bottom?: '0' | '1';
    right?: '0' | '1';

    zIndex?: '5' | '10' | '20';

    transition?: TransitionToken;
    cursor?: 'pointer';
    selectNone?: boolean;
}

