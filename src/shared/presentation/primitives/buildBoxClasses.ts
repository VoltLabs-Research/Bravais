export const buildBoxClasses = (props: BoxStyleProps): string[] => {
    const classes: string[] = [];

    if (props.display) classes.push(displayMap[props.display]);
    if (props.direction) classes.push(directionMap[props.direction]);
    if (props.align) classes.push(alignMap[props.align]);
    if (props.justify) classes.push(justifyMap[props.justify]);
    if (props.wrap) classes.push('flex-wrap');
    if (props.gap) classes.push(gapMap[props.gap]);

    if (props.p !== undefined) classes.push(paddingMap[props.p]);
    if (props.px !== undefined) classes.push(paddingXMap[props.px]);
    if (props.py !== undefined) classes.push(paddingYMap[props.py]);

    if (props.m !== undefined) classes.push('m-0');
    if (props.mt) classes.push(marginTopMap[props.mt]);
    if (props.mb) classes.push(marginBottomMap[props.mb]);
    if (props.mx) classes.push(marginXMap[props.mx]);

    if (props.bg) classes.push(backgroundMap[props.bg]);
    if (props.radius) classes.push(radiusMap[props.radius]);
    if (props.border) classes.push(borderMap[props.border]);
    if (props.position) classes.push(positionMap[props.position]);
    if (props.overflow) classes.push(overflowMap[props.overflow]);

    if (props.width) classes.push(widthMap[props.width]);
    if (props.height) classes.push(heightMap[props.height]);
    if (props.maxW) classes.push(maxWidthMap[props.maxW]);
    if (props.maxH) classes.push(maxHeightMap[props.maxH]);
    if (props.flex) classes.push(flexMap[props.flex]);

    if (props.textAlign) classes.push(textAlignMap[props.textAlign]);
    if (props.truncate) classes.push('truncate');

    if (props.shrink === '0') classes.push('shrink-0');
    if (props.minH === '0') classes.push('min-h-0');
    if (props.minW === '0') classes.push('min-w-0');

    if (props.inset === '0') classes.push('inset-0');
    if (props.top !== undefined) classes.push(insetMap.top[props.top]);
    if (props.left !== undefined) classes.push(insetMap.left[props.left]);
    if (props.bottom !== undefined) classes.push(insetMap.bottom[props.bottom]);
    if (props.right !== undefined) classes.push(insetMap.right[props.right]);

    if (props.zIndex) classes.push(zIndexMap[props.zIndex]);

    /* `transition-fast` / `transition-normal` are composites, not utilities: they
       name a property list and a duration together. They stay in composites.css. */
    if (props.transition === 'fast') classes.push('transition-fast');
    if (props.transition === 'normal') classes.push('transition-normal');
    if (props.cursor === 'pointer') classes.push('cursor-pointer');
    if (props.selectNone) classes.push('select-none');

    return classes;
};

/**
 * Keys of `BoxStyleProps`. Used by primitives to strip style-only props
 * from the rest passed through to the DOM element.
 */
export const BOX_STYLE_KEYS = [
    'display', 'direction', 'align', 'justify', 'wrap', 'gap',
    'p', 'px', 'py', 'm', 'mt', 'mb', 'mx',
    'bg', 'radius', 'border', 'position', 'overflow',
    'width', 'height', 'maxW', 'maxH', 'flex',
    'textAlign', 'truncate',
    'shrink', 'minH', 'minW',
    'inset', 'top', 'left', 'bottom', 'right',
    'zIndex',
    'transition', 'cursor', 'selectNone'
] as const;

export const splitBoxProps = <T extends BoxStyleProps>(props: T): {
    styleProps: BoxStyleProps;
    rest: Omit<T, keyof BoxStyleProps>;
} => {
    const styleProps: Record<string, unknown> = {};
    const rest: Record<string, unknown> = {};

    for (const key of Object.keys(props)) {
        if ((BOX_STYLE_KEYS as readonly string[]).includes(key)) {
            styleProps[key] = (props as Record<string, unknown>)[key];
        } else {
            rest[key] = (props as Record<string, unknown>)[key];
        }
    }

    return {
        styleProps: styleProps as BoxStyleProps,
        rest: rest as Omit<T, keyof BoxStyleProps>
    };
};
